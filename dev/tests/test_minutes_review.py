    def test_stage_proposal(self):
        self.assertIn("Staged system/staging/proposed-", self.stage_out)
        self.assertIn("2 · ABC · Action · Book UAT environment · Alan Carter ·  · no-due-date", self.stage_out)
        data = json.loads(self.proposal().read_text())
        m = data["meeting"]
        self.assertEqual(m["minutes_decision"], "pending")
        self.assertIn({"op": "copy", "from": "draft", "to": f"{ABC}/minutes/2026-10-01 Steering committee.docx"},
                      m["file_ops"])
        self.assertIn({"op": "remove", "path": self.transcript}, m["file_ops"])
        self.assertEqual(data["items"][0]["values"]["source"],
                         f"{ABC}/minutes/2026-10-01 Steering committee.docx — Actions")
        self.assertEqual(data["items"][0]["values"]["raised"], DAY)
        self.assertTrue(all(i["decision"] == "pending" for i in data["items"]))

    def test_review_bulk_rule_and_full_apply(self):
        listing = self.review("list").stdout
        self.assertIn("### Draft documents", listing)
        self.assertIn("   ↳ 2 · Decision", listing)                      # the meeting's items sit under it (BL-41)
        self.assertIn("new decision", listing)
        self.assertIn("Example Programme: 1 drafts, 2 individual, 3 routine", self.review("pending").stdout)
        out = self.review("bulk").stdout
        self.assertIn("Approved 3. Still need individual approval: 1 new decision, 1 new risk, 1 set of minutes.", out)
        # Alan edits the draft in Word, then approves the minutes, the decision and the risk one by one
        add_tracked_change_and_comment(self.v.root / self.draft)
        self.assertEqual(json.loads(self.docx("status", self.draft).stdout)["comments"], 1)
        self.review("list")
        out = self.review("approve", "1").stdout
        self.assertNotIn("labelled", out)                   # BL-121: no label is asked for
        apply_label(self.v.root / self.draft)               # Word may label it on save: cleaning must keep that label
        out = self.review("approve", "1-3").stdout
        self.assertIn("Approved 2.", out)                 # the minutes wait: the draft differs from the staged items
        self.assertIn("Action 1 owner: draft says Sara Example; in Review Omar Ali", out)
        out = self.review("approve", "1", "--sync").stdout  # Alan: "yes, update the staged proposal"
        self.assertIn("Approved 1.", out)
        self.assertIn("Accepted 2 tracked changes and removed 1 comment", out)
        self.assertIn("written 5, filed 1", self.v.run("apply").stdout)

        filed = f"{ABC}/minutes/2026-10-01 Steering committee.docx"
        text = self.docx("text", filed).stdout
        self.assertRegex(text, r"Approved by Alan on \d{1,2} [A-Z][a-z]+ 20\d\d")
        with zipfile.ZipFile(self.v.root / filed) as z:   # the label survives cleaning
            self.assertIn("MSIP_Label", z.read("docProps/custom.xml").decode())
        self.assertIn("Sara Example", text)
        self.assertIn("Sara Example | Send revised SOW to client", text)
        status = json.loads(self.docx("status", filed).stdout)
        self.assertEqual((status["tracked_changes"], status["comments"]), (0, 0))
        self.assertTrue((self.v.root / ABC / "transcripts/2026-10-01 Steering committee.vtt").exists())
        self.assertFalse((self.v.root / self.transcript).exists())
        self.assertEqual({r["id"] for r in self.v.rows("actions")}, {"ABC-A-001", "ABC-A-002"})
        self.assertEqual(self.v.rows("decisions")[0]["source"], f"{filed} — Decisions")
        # Processing the same meeting again is refused
        spec = self.v.root / "system/staging/drafts/meeting2.json"
        (self.v.root / self.transcript).write_text(TRANSCRIPT)
        spec.write_text(json.dumps(meeting_spec(self.draft, self.transcript)))
        r = self.v.run("stage", str(spec), script="minutes.py", ok=False)
        self.assertIn("Already processed on", r.stdout)

    def test_minutes_rejected_items_cite_transcript(self):
        self.review("list")
        self.review("reject", "1")
        self.review("bulk")
        self.v.run("apply")
        self.assertFalse((self.v.root / ABC / "minutes/2026-10-01 Steering committee.docx").exists())
        self.assertEqual(self.v.rows("actions")[0]["source"],
                         f"{ABC}/transcripts/2026-10-01 Steering committee.vtt — Actions")

    def test_rejected_and_duplicate_items_not_proposed_again(self):
        self.review("list")
        self.review("reject", "4")       # numbering: 1 draft, 2 decision, 3 risk, then 4 "Send revised SOW"…
        data = json.loads(self.proposal().read_text())
        rejected = [i for i in data["items"] if i["decision"] == "rejected"]
        self.assertEqual(len(rejected), 1)
        self.review("bulk")
        self.review("approve", "1-3")
        self.v.run("apply")
        (self.v.root / self.transcript).write_text(TRANSCRIPT + "\n")      # a different recording of the same topics
        make = self.v.root / "system/staging/drafts/again.json"
        again = "system/staging/drafts/2026-10-01 ABC Steering follow-up.docx"   # BL-260: a transcript is staged with its draft
        values = self.v.root / "system/staging/values.json"
        values.write_text(json.dumps(fill_values()))
        self.docx("fill", "system/templates/minutes-template.docx", str(values), str(self.v.root / again))
        spec = meeting_spec(again, self.transcript)
        spec["title"] = "ABC Steering follow-up"
        make.write_text(json.dumps(spec))
        out = self.v.run("stage", str(make), script="minutes.py").stdout
        self.assertIn("skipped (already in the tracker as ABC-A-001)", out)
        self.assertIn("skipped (rejected before)", out)


