class RefreshTests(unittest.TestCase):
    """Re-extract: the edited draft rebuilds the meeting's items; decisions on matching items are kept."""

    def setUp(self):
        self.v = Vault()
        self.v.run("init")
        self.transcript = "inbox/Recording 2026-10-01.vtt"
        (self.v.root / self.transcript).write_text(TRANSCRIPT)
        self.draft = "system/staging/drafts/2026-10-01 Steering committee.docx"
        self.fill(fill_values())
        spec = self.v.root / "system/staging/drafts/meeting.json"
        spec.write_text(json.dumps(meeting_spec(self.draft, self.transcript)))
        self.v.run("stage", str(spec), script="minutes.py")
        self.prop = next((self.v.root / "system/staging").glob("proposed-*.json"))

    def tearDown(self):
        self.v.cleanup()

    def fill(self, values):
        f = self.v.root / "system/staging/values.json"
        f.write_text(json.dumps(values))
        self.v.run("fill", "system/templates/minutes-template.docx", str(f), str(self.v.root / self.draft),
                   script="docx_tools.py", cwd=self.v.root)

    def items(self):
        return json.loads(self.prop.read_text())["items"]

    def test_refresh_follows_the_edited_draft(self):
        data = json.loads(self.prop.read_text())
        for i in data["items"]:
            if i["table"] == "actions" and i["values"]["description"].startswith("Send revised SOW"):
                i["decision"] = "approved"                       # a decision already made
        self.prop.write_text(json.dumps(data))
        edited = fill_values()                                   # Alan edits the draft in Word:
        edited["ACTIONS"] = [{"A_OWNER": "Sara Example", "A_TEXT": "Send revised SOW to the client",
                              "A_DUE": "09-10-2026"}]           # owner, wording and date changed; UAT action deleted
        edited["DECISIONS"] = edited["DECISIONS"] + ["Weekly sponsor call until go-live — proposed by Jane Doe."]
