class ReviewCommandTests(unittest.TestCase):
    def setUp(self):
        self.v = Vault()
        self.v.run("init")

    def tearDown(self):
        self.v.cleanup()

    def review(self, *args, ok=True):
        return self.v.run(*args, script="review.py", ok=ok)

    def test_assign_edit_and_conflicts(self):
        base = {"source": "Email · From: Jane <j@client.com> · Subject: SOW · Sent: 2026-10-01 09:00", "raised": "2026-10-01"}
        p = self.v.propose("sweep", [
            {"n": 1, "op": "new", "table": "actions", "match": "possible", "flags": [], "decision": "pending",
             "values": {**base, "project": "ABC", "description": "Confirm data owner"}},
            {"n": 2, "op": "new", "table": "actions", "match": "strong", "flags": [], "decision": "pending",
             "values": {**base, "project": "ABC", "description": "Chase legal on SOW"}},
        ])
        listing = self.review("list").stdout
        self.assertLess(listing.index("## Needs a project"), listing.index("## Example Programme"))
        self.assertIn("needs a project first", self.review("approve", "1").stdout)
        self.review("assign", "1", "ABC")
        self.review("list")
        out = self.review("edit", "2", "owner=Sara Example", "due_date=15-10-2026").stdout
        self.assertIn("edited and approved", out)
        items = json.loads(p.read_text())["items"]
        self.assertEqual(items[0]["match"], "strong")
        self.assertEqual(items[1]["values"]["due_date"], "2026-10-15")
        bad = self.review("edit", "1", "due_date=31-02-2026", ok=False).stdout
        self.assertIn("not approved", bad)
        # Conflict: keep or override
        self.review("approve", "2")
        self.v.run("apply", str(p))
        self.v.propose("xl", [{"n": 1, "op": "update", "table": "actions", "id": "ABC-A-001",
                               "changes": {"owner": "Omar Ali"}, "based_on": "2026-01-01 00:00:00.000",
                               "decision": "pending", "match": "strong", "flags": []}])
        self.v.run("validate", str(self.v.root / "system/staging/proposed-xl.json"))
        self.review("list")
        self.assertIn("keep", self.review("approve", "1").stdout)   # conflicts come first in the project
        self.review("override", "1")
        self.v.run("apply", str(self.v.root / "system/staging/proposed-xl.json"))
        self.assertEqual(self.v.rows("actions")[0]["owner"], "Omar Ali")


class DocxUnitTests(unittest.TestCase):
    def test_teams_word_transcript(self):
        sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "system" / "scripts"))
        import tempfile
        import minutes
        W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
        lines = ["ABC Steering-20261001_100000-Meeting Transcript", "October 1, 2026, 6:00AM", "19m 24s",
                 "621792274320Alan Carter started transcription", "576072292608Jane Doe 0:03It&apos;s agreed.",
                 "576072292608Jane Doe 0:09Go-live stays.", "576072292608Omar Ali 1:02:10I&apos;ll send it."]
        body = "".join(f"<w:p><w:r><w:t>{t}</w:t></w:r></w:p>" for t in lines)
        path = Path(tempfile.mkdtemp()) / "t.docx"
        with zipfile.ZipFile(path, "w") as z:
            z.writestr("word/document.xml", f'<w:document xmlns:w="{W}"><w:body>{body}</w:body></w:document>')
        text = minutes.teams_docx_text(path)
        web = ("Jane Doe 0:09Done. AW Amy Wood 0 minutes 8 seconds0:08 Amy Wood 0 minutes 8 seconds "
               "What has feedback been? Amy Wood 0 minutes 14 seconds Any at all? JD Jane Doe 1 minute1:00 "
               "Jane Doe 1 minute Good so far. Alan Carter 41 minutes 58 seconds41:58 Alan Carter 41 minutes 58 seconds "
               "Thank you.")
        path2 = path.with_name("t2.docx")
        with zipfile.ZipFile(path2, "w") as z:
            z.writestr("word/document.xml", f'<w:document xmlns:w="{W}"><w:body><w:p><w:r><w:t>{web}</w:t></w:r>'
                                            '</w:p></w:body></w:document>')
        self.assertEqual(minutes.teams_docx_text(path2).splitlines()[-4:], [
            "[Recording part 2]", "Amy Wood (0:08): What has feedback been? Any at all?",
            "Jane Doe (1:00): Good so far.", "Alan Carter (41:58): Thank you."])
        self.assertIn("October 1, 2026, 6:00AM\n19m 24s\nAlan Carter started transcription", text)
        self.assertIn("Jane Doe (0:03): It's agreed. Go-live stays.\nOmar Ali (1:02:10): I'll send it.", text)

