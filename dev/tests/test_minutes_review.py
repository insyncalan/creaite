def apply_label(docx):
    """What Word does on save: add the sensitivity-label properties (fictional label ID)."""
    with zipfile.ZipFile(docx) as z:
        parts = {i.filename: z.read(i.filename) for i in z.infolist()}
    parts["docProps/custom.xml"] = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Properties '
        'xmlns="http://schemas.openxmlformats.org/officeDocument/2006/custom-properties" '
        'xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes">'
        '<property fmtid="{D5CDD505-2E9C-101B-9397-08002B2CF9AE}" pid="2" '
        'name="MSIP_Label_00000000-0000-0000-0000-000000000000_Enabled"><vt:lpwstr>true</vt:lpwstr></property>'
        '</Properties>').encode()
    parts["_rels/.rels"] = parts["_rels/.rels"].decode().replace("</Relationships>", (
        '<Relationship Id="rIdLabel" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/'
        'custom-properties" Target="docProps/custom.xml"/></Relationships>')).encode()
    parts["[Content_Types].xml"] = parts["[Content_Types].xml"].decode().replace("</Types>", (
        '<Override PartName="/docProps/custom.xml" '
        'ContentType="application/vnd.openxmlformats-officedocument.custom-properties+xml"/></Types>')).encode()
    with zipfile.ZipFile(docx, "w", zipfile.ZIP_DEFLATED) as z:
        for name, raw in parts.items():
            z.writestr(name, raw)


def add_tracked_change_and_comment(docx):
    """What Alan does in Word: change an owner as a tracked change and add a comment."""
    with zipfile.ZipFile(docx) as z:
        parts = {i: z.read(i.filename) for i in z.infolist()}
    if not any(i.filename == "word/comments.xml" for i in parts):   # Word creates the part on the first comment
        W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
        parts[zipfile.ZipInfo("word/comments.xml")] = f'<w:comments xmlns:w="{W}"/>'.encode()
        for info in list(parts):
            if info.filename == "word/_rels/document.xml.rels":
                parts[info] = parts[info].decode().replace("</Relationships>", (
                    '<Relationship Id="rIdC1" Type="http://schemas.openxmlformats.org/officeDocument/2006/'
                    'relationships/comments" Target="comments.xml"/></Relationships>')).encode()
            if info.filename == "[Content_Types].xml":
                parts[info] = parts[info].decode().replace("</Types>", (
                    '<Override PartName="/word/comments.xml" ContentType="application/vnd.openxmlformats-'
                    'officedocument.wordprocessingml.comments+xml"/></Types>')).encode()
    out = {}
    for info, raw in parts.items():
        if info.filename == "word/document.xml":
            xml = raw.decode("utf-8")
            run = re.findall(r"<w:r>(?:(?!</w:r>).)*<w:t[^>]*>Omar Ali</w:t></w:r>", xml, re.S)[-1]  # actions table
            new_run = run.replace("Omar Ali", "Sara Example")
            deleted = run.replace("<w:t", "<w:delText").replace("</w:t>", "</w:delText>")
            change = (f'<w:del w:id="91" w:author="Alan Carter" w:date="2026-10-02T09:00:00Z">{deleted}</w:del>'
                      f'<w:ins w:id="92" w:author="Alan Carter" w:date="2026-10-02T09:00:00Z">{new_run}</w:ins>')
            xml = xml.replace(run, change, 1)
            m = re.search(r"<w:r>(?:(?!</w:r>).)*<w:t[^>]*>Omar is revising the SOW.</w:t></w:r>", xml, re.S)
            xml = xml.replace(m.group(), '<w:commentRangeStart w:id="5"/>' + m.group() + '<w:commentRangeEnd w:id="5"/>'
                              '<w:r><w:commentReference w:id="5"/></w:r>', 1)
            raw = xml.encode("utf-8")
        elif info.filename == "word/comments.xml":
            comment = ('<w:comment w:id="5" w:author="Alan Carter"><w:p><w:r><w:t>Check scope</w:t></w:r></w:p>'
                       '</w:comment></w:comments>')
            xml = raw.decode("utf-8")
            xml = xml.replace("</w:comments>", comment) if "</w:comments>" in xml else xml[:-2] + ">" + comment
            raw = xml.encode("utf-8")
        out[info] = raw
    with zipfile.ZipFile(docx, "w", zipfile.ZIP_DEFLATED) as z:
        for info, raw in out.items():
            z.writestr(info, raw)


class MeetingFlowTests(unittest.TestCase):
    def setUp(self):
        self.v = Vault()
        self.v.run("init")
        self.transcript = "inbox/Recording 2026-10-01.vtt"
        (self.v.root / self.transcript).write_text(TRANSCRIPT)
        stem = self.v.run("filename", "--date", DAY, "--title", TITLE, script="minutes.py").stdout.strip()
        self.assertEqual(stem, "2026-10-01 Steering committee")
        self.draft = f"system/staging/drafts/{stem}.docx"
        values = self.v.root / "system/staging/values.json"
        values.write_text(json.dumps(fill_values()))
        self.v.run("fill", "system/templates/minutes-template.docx", str(values), str(self.v.root / self.draft),
                   script="docx_tools.py", cwd=self.v.root)
        spec = self.v.root / "system/staging/drafts/meeting.json"
        spec.write_text(json.dumps(meeting_spec(self.draft, self.transcript)))
        self.stage_out = self.v.run("stage", str(spec), script="minutes.py").stdout

    def tearDown(self):
        self.v.cleanup()

    def docx(self, *args, ok=True):
        return self.v.run(*args, script="docx_tools.py", ok=ok, cwd=self.v.root)

    def review(self, *args, ok=True):
        return self.v.run(*args, script="review.py", ok=ok)

    def proposal(self):
        return next((self.v.root / "system/staging").glob("proposed-*.json"))

    def test_a_draft_is_approved_without_any_label(self):
        """BL-121: a draft straight from the template, with no Word sensitivity label, is approved; nothing asks for one."""
        with zipfile.ZipFile(self.v.root / self.draft) as z:
            self.assertNotIn("MSIP_Label", z.read("docProps/custom.xml").decode() if "docProps/custom.xml" in z.namelist() else "")
        self.review("list")
        out = self.review("approve", "1", "--as-staged").stdout
        self.assertIn("Minutes approved", out)
        self.assertNotIn("label", out.lower())

    def test_a_draft_open_in_word_is_still_refused(self):
        (self.v.root / "system/staging/drafts/~$26-10-01 Steering committee.docx").write_text("lock")
        self.review("list")
        out = self.review("approve", "1", "--as-staged").stdout
        self.assertIn("is open in Word", out)
        self.assertNotIn("Minutes approved", out)

    def test_the_unlabelled_option_is_gone(self):
        self.review("list")
        r = self.review("approve", "1", "--unlabelled", ok=False)
        self.assertEqual(r.returncode, 2)
        self.assertIn("no longer an option", r.stdout)
        self.assertNotIn("Minutes approved", r.stdout)                                      # nothing was approved by the refused command
        self.assertNotIn("def labelled", (self.v.root / "system/scripts/review.py").read_text())
        defaults = json.loads((self.v.root / "system/templates/settings-defaults.json").read_text())
        self.assertNotIn("documents", defaults)

    def test_transcript_and_key(self):
        text = self.v.run("transcript", self.transcript, script="minutes.py", cwd=self.v.root).stdout
        self.assertIn("Alan Carter: Morning all, this is the ABC steering committee. First item is the SOW.", text)
        key = json.loads(self.v.run("key", "--date", DAY, "--title", TITLE, "--transcript", self.transcript,
                                    script="minutes.py", cwd=self.v.root).stdout)
        self.assertTrue(key["key"].startswith("fp:2026-10-01|steering committee|"))
        self.assertIsNone(key["processed_on"])

    def test_draft_filled(self):
        text = self.docx("text", self.draft).stdout
        self.assertNotIn("{{", text)
        self.assertIn("Draft, generated by creaite", text)
        self.assertIn("Omar Ali | Send revised SOW to client | 02-10-2026", text)
        self.assertIn("Alan Carter | Book UAT environment | Not set", text)
        self.assertIn("Attendees: Jane Doe (Client); Alan Carter, Omar Ali (Example Co)", text)
        self.assertIn("SOW\nOmar is revising the SOW.\n PRIORITY   Sign-off is needed before go-live.\nGo-live", text)
