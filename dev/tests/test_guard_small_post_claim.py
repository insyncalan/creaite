DIFFS = ("reach-post-claim.diff", "live-server-post-hook.diff")
R, L = "system/scripts/reach.py", "system/scripts/live_server.py"
_ROOT = Path(__file__).resolve().parents[2]


def _as_now(path, *pairs):
    """(old, new) for the first pair whose old text is in the file as it stands: #283's guarded diff (Read again) gives the
    PostToolUse to mode "reextract" too, so the lines these mutants change read differently once it is applied."""
    text = (_ROOT / path).read_text(encoding="utf-8")
    return next(((o, n) for o, n in pairs if o in text), pairs[0])


MUTATIONS = {
    "first-sight": ("a file with no print is the run's at first sight again", R,
                    "    return isinstance(was, list) and _print(rp) == was", "    return was is None or _print(rp) == was"),
    "post-matches-any": ("a PostToolUse records every pending call's files", R,
                         '        return isinstance(use_id, str) and entry["id"] == use_id', "        return True"),
    "post-any-run": ("a PostToolUse for another run records", R, *_as_now(
        R, ("    _HOOK.update(run=run)\n    try:\n        key = _call_key",
            "    _HOOK.update(run=(guard_run() or {}).get('run'))\n    try:\n        key = _call_key"),
        ("    _HOOK.update(run=run, mode=mode)\n    try:\n        key = _call_key",
         "    _HOOK.update(run=(guard_run() or {}).get('run'), mode=mode)\n    try:\n        key = _call_key"))),
    "pending-unbounded": ("pending grows without limit", R, "[-PENDING_MAX:]", ""),
    "no-post-hook": ("the Process run's --settings has no PostToolUse", L, *_as_now(
        L, ('    if mode == "process":       # #264 round 3', '    if False:       # #264 round 3'),
        ('    if mode in reach.PROCESS_MODES:     # #264 round 3', '    if False:     # #264 round 3'))),
}
TPL = "system/templates/minutes-template.docx"
VALUES = {"MEETING_TITLE": "ABC Pilot readiness review", "STATUS_LINE": "Draft, generated by creaite. Not yet reviewed.",
          "MEETING_WHEN": "20 October 2026, 10:00-10:30", "ATTENDEES": "Jane Doe (Client); Alan Carter, Omar Ali (Example Co)",
          "SUMMARY": ["The meeting went through the plan."], "UPDATES": [{"heading": "Plan", "items": ["On track."]}],
          "DECISIONS": [], "RISKS_ISSUES": [], "OPEN_QUESTIONS": [], "SOURCE": "Teams transcript, 20 October 2026",
          "ACTIONS": [{"A_OWNER": "Omar Ali", "A_TEXT": "Send the checklist", "A_DUE": "Not set"}]}
D = "system/staging/drafts/"
DAY = "2026-10-20"

# The stand-in for Claude Code: each step is a PreToolUse (the run's hook), the tool itself (Write writes, Bash runs the script),
# and, when the tool succeeded, the PostToolUse hook, exactly from the run's --settings. Other steps stand for another flow.
HARNESS = r'''
import json, os, shlex, subprocess, sys
sys.path.insert(0, "system/scripts")
import live_server, reach
a = json.loads(sys.stdin.read())
D = "system/staging/drafts/"
reach.start_run(a["run"], "process", {}, None, files=a["files"])
hooks = json.loads(live_server.guard_settings(a["run"], "process"))["hooks"]
pre = hooks["PreToolUse"][0]["hooks"][0]["command"]
post = hooks["PostToolUse"][0]["hooks"][0]["command"] if "PostToolUse" in hooks else None
def hook(cmd, tool, inp, uid):
    return subprocess.run(cmd, shell=True, input=json.dumps({"tool_name": tool, "tool_input": inp, "tool_use_id": uid}),
                          capture_output=True, text=True, timeout=120).returncode
out = []
for n, s in enumerate(a["steps"]):
    if "other" in s:                                    # another creaite flow writes a drafts file (a new file in its place)
        p = D + s["other"]
        open(p + ".tmp", "w").write('{"another": "flow"}'); os.replace(p + ".tmp", p)
        out.append(None); continue
    if "post_as" in s:                                  # a stray PostToolUse: another run's, or another call's
        cmd = post.replace("--run " + shlex.quote(a["run"]), "--run " + shlex.quote(s["post_as"])) if post else None
        if cmd:
            hook(cmd, s["tool"], s["inp"], s.get("id", "stray"))
        out.append(None); continue
    uid = s.get("id", "tu-%d" % n)
    tool, inp = s["tool"], dict(s["inp"])
    allowed = hook(pre, tool, inp, uid) == 0
    ok = False
    if allowed and not s.get("fails"):
        if tool == "Write":
            open(inp["file_path"], "w").write(s.get("content", "{}")); ok = True
        elif tool == "Bash":
            w = shlex.split(inp["command"])
            ok = subprocess.run([sys.executable, "system/scripts/" + w[1], *w[2:]], capture_output=True, text=True,
                                timeout=300).returncode == 0
    if allowed and ok and post:
        hook(post, tool, inp, uid)
    out.append([allowed, ok])
d = json.loads(reach.RUN_FILE.read_text())
print(json.dumps({"out": out, "made": sorted(os.path.basename(m) for m in d.get("made", [])),
                  "staged": sorted(p.name for p in reach.paths.STAGING.glob("proposed-*.json") if p.name not in d.get("before", [])),
                  "settings": {m: sorted(json.loads(live_server.guard_settings("x", m))["hooks"]) for m in ("process", "ask", "confirmed", "sweep")}}))
'''


def write(path, content="{}"):
    return {"tool": "Write", "inp": {"file_path": path}, "content": content}


def bash(words, **kw):
    return {"tool": "Bash", "inp": {"command": "system/scripts/run " + words}, **kw}


class ClaimOnlyWhenTheToolReturns(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.v = scratch(DIFFS, MUTATIONS)
        cls.files = put_samples(cls.v)
        (cls.v.root / D).mkdir(parents=True, exist_ok=True)

    @classmethod
    def tearDownClass(cls):
        cls.v.cleanup()

    def spec(self, name, draft=None):
        s = {"title": "Pilot readiness review", "date": DAY, "projects": ["ABC"], "transcript": self.files[0],
             "minutes": {"start": "10:00", "end": "10:30", "attendees": "Jane Doe, Omar Ali, Alan Carter",
                         "summary": ["The meeting went through the plan."], "updates": [{"heading": "Plan", "items": ["On track."]}],
                         "open_questions": []},
             "items": [{"table": "actions", "values": {"project": "ABC", "description": f"Send the {name} checklist",
                                                       "owner": "Omar Ali", "raised": DAY}}]}
        if draft:                                          # a Word draft: the minutes are in it, not a minutes record
            s["draft"] = D + draft
            s.pop("minutes")
        return json.dumps(s)

    def run_steps(self, steps, run="p-1"):
        steps = [dict(s, inp={k: (str(self.v.root / v) if k == "file_path" else v) for k, v in s["inp"].items()})
                 if "inp" in s else s for s in steps]
        return in_vault(self.v, HARNESS, {"run": run, "files": self.files, "steps": steps},
                        timeout=900)

    def test_settings_add_the_post_hook_to_process_only(self):
        got = self.run_steps([])
        self.assertEqual(got["settings"]["process"], ["PostToolUse", "PreToolUse"])
        for m in ("ask", "confirmed", "sweep"):
            self.assertEqual(got["settings"][m], ["PreToolUse"], m)

    def test_the_normal_process_flow_still_works_end_to_end(self):
        """Write the values file, fill the Word draft, write the spec, map names, stage: each allowed and run for real, and the
        meeting reaches staging with its Word draft."""
        got = self.run_steps([write(D + "e2e-values.json", json.dumps(VALUES)),
                              bash(f"docx_tools.py fill {TPL} {D}e2e-values.json {D}e2e-minutes.docx"),
                              write(D + "e2e-spec.json", self.spec("e2e", "e2e-minutes.docx")),
                              bash(f"propose.py people map {D}e2e-spec.json"),
                              bash(f"minutes.py stage {D}e2e-spec.json")])
        self.assertEqual(got["out"], [[True, True]] * 5, got)
        self.assertTrue(got["staged"], got)
        self.assertIn("e2e-minutes.docx", got["made"])

    def test_a_refused_fill_claims_nothing(self):
        got = self.run_steps([write(D + "r pics.json", json.dumps({"BODY": [{"image": "~/Pictures/a.png"}]})),
                              bash(f"docx_tools.py fill {TPL} '{D}r pics.json' '{D}r minutes.docx'"),
                              {"other": "r minutes.docx"},
                              write(D + "r spec.json", self.spec("r", "r minutes.docx")),
                              bash(f"minutes.py stage '{D}r spec.json'")])
        self.assertEqual(got["out"][1][0], False, got)
        self.assertNotIn("r minutes.docx", got["made"])
        self.assertEqual(got["out"][4][0], False, got)

    def test_an_allowed_fill_whose_tool_fails_makes_nothing_the_runs(self):
        """The fill is allowed but its tool fails (no file, no PostToolUse); another flow then writes that exact name: staging it
        as this run's Word draft is refused, and the run can't fill over it either."""
        got = self.run_steps([write(D + "f values.json", "{}"),
                              bash(f"docx_tools.py fill {TPL} '{D}f values.json' '{D}f minutes.docx'", fails=True),
                              {"other": "f minutes.docx"},
                              write(D + "f spec.json", self.spec("f", "f minutes.docx")),
                              bash(f"minutes.py stage '{D}f spec.json'"),
                              bash(f"docx_tools.py fill {TPL} '{D}f values.json' '{D}f minutes.docx'")])
        self.assertEqual(got["out"][1][0], True, got)
        self.assertEqual(got["out"][4][0], False, got)
        self.assertEqual(got["out"][5][0], False, got)

    def test_a_values_file_swapped_before_its_first_use_is_refused(self):
        """The run writes its values file (its PostToolUse records it); another flow puts a file in its place before the fill: the
        fill from it is refused. A Write whose tool fails leaves the name unclaimed for another flow's file too."""
        got = self.run_steps([write(D + "s values.json", "{}"),
                              {"other": "s values.json"},
                              bash(f"docx_tools.py fill {TPL} '{D}s values.json' '{D}s minutes.docx'"),
                              dict(write(D + "s2 values.json", "{}"), fails=True),
                              {"other": "s2 values.json"},
                              bash(f"docx_tools.py fill {TPL} '{D}s2 values.json' '{D}s2 minutes.docx'"),
                              bash(f"propose.py people map '{D}s2 values.json'")])
        self.assertEqual([o[0] if o else o for o in got["out"]], [True, None, False, True, None, False, False], got)

    def test_a_stray_post_records_nothing(self):
        """A PostToolUse for another call (another tool_use_id) or for another run never fingerprints the failed fill's name."""
        fill = bash(f"docx_tools.py fill {TPL} '{D}p values.json' '{D}p minutes.docx'", fails=True, id="tu-fill")
        got = self.run_steps([write(D + "p values.json", "{}"),
                              fill,
                              {"other": "p minutes.docx"},
                              write(D + "p other.json", "{}"),
                              dict(fill, post_as="p-other"),
                              write(D + "p spec.json", self.spec("p", "p minutes.docx")),
                              bash(f"minutes.py stage '{D}p spec.json'")])
        self.assertEqual(got["out"][6][0], False, got)

    def test_pending_calls_are_capped(self):
        """300 allowed Writes whose tool never returns keep only the 64 newest pending calls (run.json stays small); the newest
        call's PostToolUse still records its file, and a dropped call's name is never the run's."""
        code = ("import os, reach\n"
                "reach.start_run('p-cap', 'process', {}, None, files=[])\n"
                "d = 'system/staging/drafts/'\n"
                "for i in range(300):\n"
                "    inp = {'file_path': os.path.realpath(d) + '/cap-%d.json' % i}\n"
                "    assert reach.decide('Write', inp, 'process', 'p-cap', False, 'cap-%d' % i)[0]\n"
                "open(d + 'cap-299.json', 'w').write('{}')\n"
                "reach.post_tool('Write', inp, 'p-cap', 'cap-299')\n"
                "open(d + 'cap-0.json', 'w').write('{}')\n"
                "reach.post_tool('Write', {'file_path': os.path.realpath(d) + '/cap-0.json'}, 'p-cap', 'cap-0')\n"
                "reach._HOOK.update(run='p-cap')\n"
                "from pathlib import Path\n"
                "own = [reach._runs_own(Path(os.path.realpath(d + n))) for n in ('cap-299.json', 'cap-0.json')]\n"
                "print(json.dumps({'pending': len(json.loads(reach.RUN_FILE.read_text())['pending']), "
                "'size': len(json.dumps(json.loads(reach.RUN_FILE.read_text())['pending'])), 'own': own}))")
        got = in_vault(self.v, code, timeout=600)
        self.assertLessEqual(got["pending"], 64, got)
        self.assertLess(got["size"], 20_000, got)            # the pending list itself (names claimed stay in "made")
        self.assertEqual(got["own"], [True, False], got)


