"""guard-small (3), #264 round 2 LOW leftover: a Process run's file is its own only once its own tool has returned. PROPOSAL test
for dev/proposals/guard-small/reach-post-claim.diff and live-server-post-hook.diff (reach.py and live_server.py are guarded).

Run: python3 dev/tests/test_guard_small_post_claim.py
Fail-first: GUARD_SMALL_UNPATCHED=1 python3 dev/tests/test_guard_small_post_claim.py

Before: the PreToolUse hook claimed a drafts name for the run (run.json "made") and its fingerprint was taken at first sight, the
next time the hook looked. So if an allowed `fill` then failed to make its file, or another flow put a file in place of the run's
values file between the run's Write and its first use, that other file was taken as the run's own (`minutes.py stage` with it as
the Word draft, or a fill from it, was allowed). After: the fingerprint is taken by a PostToolUse hook (`reach.py hook ... --event
post`, which live_server adds to a Process run's --settings) when the run's own tool returns, for the files that call's PreToolUse
let it write (matched by tool_use_id, else by the call itself). No PostToolUse, no fingerprint: not the run's (fail closed).

Every call here goes through the real hook commands from live_server.guard_settings (as Claude Code runs them), in a scratch copy.
"""
