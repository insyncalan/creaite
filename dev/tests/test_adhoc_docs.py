"""Tests for ad-hoc branded Word documents (BL-75): report.py adhoc and adhoc-data, docx_tools.py build-adhoc.

Run: python3 dev/tests/test_adhoc_docs.py
Each test builds a throwaway vault (test_tracker.Vault) with fictional items and runs the real scripts there.
"""
import json
import os
import subprocess
import sys
import unittest
import zipfile
from pathlib import Path
from xml.dom import minidom

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_tracker import ABC, REPO, Vault, action  # noqa: E402

NOW = "2026-10-07 10:00"                 # a Wednesday


def raid(n, type_, **v):
    values = {"project": "ABC", "type": type_, "description": "Data access delayed", "impact": "High", "likelihood": "High",
              "raised": "2026-10-01", "source": f"{ABC}/minutes/x.docx — Risks", **v}
    return {"n": n, "op": "new", "table": "raid", "values": values, "match": "strong", "flags": [], "decision": "approved"}


class AdhocBase(unittest.TestCase):
    def setUp(self):
        self.v = Vault()
        self.v.run("init")
        import sqlite3
        from contextlib import closing
        with closing(sqlite3.connect(self.v.root / "system/tracker.db")) as con:
            con.execute("INSERT INTO projects (code, name, updated_at) VALUES ('DEF', 'Digital Enablement', '2026-10-01 00:00:00')")
            con.commit()
        self.v.propose("seed", [
            action(1, description="Send revised SOW to client", owner="Omar Ali", due_date="2026-10-02"),         # overdue
            action(2, description="Book the UAT environment", owner="Alan Carter", due_date="2026-10-20", priority="High"),
            action(3, description="Chase legal", owner="Omar Ali (Enable)", due_date="2026-10-15"),
            action(4, description="Closed thing", status="Closed", closed="2026-10-02"),
            action(5, project="DEF", description="Agree pilot criteria", owner="Sam", due_date="2026-10-09"),
            raid(6, "Risk"), raid(7, "Issue", description="Licences not ordered", response_action="Ordering them"),
            {"n": 8, "op": "new", "table": "decisions", "match": "strong", "flags": [], "decision": "approved",
             "values": {"project": "ABC", "decision": "Go-live moves two weeks", "made_by": "Jane Doe", "date": "2026-10-01",
                        "source": f"{ABC}/minutes/x.docx — Decisions"}}])
        self.v.run("apply")

    def tearDown(self):
        self.v.cleanup()

    def report(self, *args, ok=True):
        r = subprocess.run([sys.executable, str(self.v.root / "system/scripts/report.py"), *args], cwd=self.v.root,
                           capture_output=True, text=True, env={**os.environ, "CREAITE_NOW": NOW})
        if ok:
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        return r

    def build(self, spec, ok=True):
        f = self.v.root / "spec.json"
        f.write_text(json.dumps(spec))
        return self.report("adhoc", str(f), ok=ok)

    def text(self, rel):
        return subprocess.run([sys.executable, str(self.v.root / "system/scripts/docx_tools.py"), "text", str(self.v.root / rel)],
                              capture_output=True, text=True).stdout

    def drafts(self):
        return sorted(p.name for p in (self.v.root / "system/staging/drafts").glob("*.docx"))


class AdhocDocumentTests(AdhocBase):
    def test_an_actions_register_from_the_tracker(self):
        out = self.build({"title": "Open actions", "subtitle": "Actions register",
                          "sections": [{"heading": "All projects", "tracker": {"table": "actions", "group_by": "project"}}]}).stdout
        self.assertIn("system/staging/drafts/2026-10-07 Open actions.docx (2 tables, 4 rows)", out)
        self.assertEqual(self.drafts(), ["2026-10-07 Open actions.docx"])
        text = self.text("system/staging/drafts/2026-10-07 Open actions.docx")
        self.assertIn("Open actions\nActions register\nDraft, generated by creaite on 7 October 2026. Internal", text)
        self.assertIn("07-10-2026", text)                                                      # the date, DD-MM-YYYY
        self.assertIn("Example Programme\n3 actions.", text)                              # a section per project
        self.assertIn("Digital Enablement\n1 action.", text)
        self.assertIn("ID | Action | Owner | Due | Priority | Status", text)
        self.assertIn("ABC-A-001 | Send revised SOW to client | Omar Ali | 02-10-2026 · 5 days late | Medium | Open", text)
        self.assertNotIn("Closed thing", text)                                                 # open items by default
        self.assertTrue(text.index("Send revised SOW") < text.index("Chase legal") < text.index("Book the UAT"))   # by due date

    def test_filters(self):
        def rows(q):
            return [r[0] for r in json.loads(self.report("adhoc-data", *q).stdout)["rows"]]
        self.assertEqual(rows(["actions", "--owner", "Omar Ali"]), ["ABC-A-001", "ABC-A-003"])        # "Name (Company)" too
        self.assertEqual(rows(["actions", "--project", "DEF"]), ["DEF-A-001"])
        self.assertEqual(rows(["actions", "--status", "closed"]), ["ABC-A-004"])
        self.assertEqual(sorted(rows(["actions", "--status", "all"])), ["ABC-A-001", "ABC-A-002", "ABC-A-003", "ABC-A-004", "DEF-A-001"])
        self.assertEqual(rows(["actions", "--due-before", "2026-10-09"]), ["ABC-A-001", "DEF-A-001"])
        self.assertEqual(rows(["raid", "--type", "Issue"]), ["ABC-006"])
        self.assertEqual(rows(["decisions"]), ["ABC-D-007"])
        data = json.loads(self.report("adhoc-data", "raid").stdout)
        self.assertEqual(data["columns"], ["ID", "Type", "Description", "Owner", "Priority", "Response", "Due", "Status"])
        self.assertEqual(data["count"], 2)

    def test_overdue_lists_only_open_late_items(self):
        data = json.loads(self.report("adhoc-data", "actions", "--overdue").stdout)
        self.assertEqual([r[0] for r in data["rows"]], ["ABC-A-001"])                           # DEF-A-001 is due 09-10: not yet

    def test_choose_columns_and_a_literal_table_and_free_text(self):
        self.build({"title": "Mixed", "sections": [
            {"heading": "Intro", "paragraphs": ["Prepared for the steering committee."], "bullets": ["One", "Two"]},
            {"heading": "Risks", "tracker": {"table": "raid", "columns": ["id", "description", "response_action"], "status": "all"}},
            {"heading": "Owners", "table": {"columns": ["Name", "Role"], "rows": [["Omar Ali", "PM"], ["Jane Doe", "Sponsor"]]},
             "note": "As of today."}], "source": "Tracker and Alan"})
        text = self.text("system/staging/drafts/2026-10-07 Mixed.docx")
        self.assertIn("Prepared for the steering committee.\nOne\nTwo", text)
        self.assertIn("ID | Description | Response\nABC-005 | Data access delayed |", text)
        self.assertIn("Name | Role\nOmar Ali | PM\nJane Doe | Sponsor", text)
        self.assertTrue(text.rstrip().endswith("Tracker and Alan"))

    def test_the_file_is_a_branded_word_document(self):
        self.build({"title": "Branded", "landscape": True, "sections": [{"heading": "A", "tracker": {"table": "actions"}}]})
        path = self.v.root / "system/staging/drafts/2026-10-07 Branded.docx"
        with zipfile.ZipFile(path) as z:
            doc = z.read("word/document.xml").decode()
            minidom.parseString(doc)                                                           # well-formed
            self.assertIn("<w:drawing", doc)                                                   # the wordmark
            self.assertIn('w:orient="landscape"', doc)
            self.assertIn("Branded", z.read("docProps/core.xml").decode())
            template = zipfile.ZipFile(REPO / "system/templates/adhoc-template.docx")
            self.assertEqual(sorted(z.namelist()), sorted(template.namelist()))                # same parts as the template
            self.assertEqual(z.read("word/styles.xml"), template.read("word/styles.xml"))      # same house styles

    def test_it_never_overwrites_and_stays_in_drafts(self):
        spec = {"title": "Same name: a/b?", "sections": [{"heading": "A", "paragraphs": ["x"]}]}
        self.build(spec)
        self.build(spec)
        self.assertEqual(self.drafts(), ["2026-10-07 Same name a b 2.docx", "2026-10-07 Same name a b.docx"])
        self.assertEqual([p.name for p in (self.v.root / "system/staging/drafts").iterdir() if p.suffix != ".docx"], [])  # no .values.json or .tmp
        self.assertFalse(list(self.v.root.glob("*.docx")))                                      # nothing outside the drafts folder

    def test_it_refuses_bad_specs_and_writes_nothing(self):
        for spec, msg in (({"sections": []}, "needs a title"),
                          ({"title": "X", "sections": [{"tracker": {"table": "nope"}}]}, "table must be one of"),
                          ({"title": "X", "sections": [{"tracker": {"table": "actions", "bogus": 1}}]}, "unknown key bogus"),
                          ({"title": "X", "sections": [{"tracker": {"table": "actions", "columns": ["owner", "salary"]}}]}, "no column salary"),
                          ({"title": "X", "sections": [{"table": {"columns": ["A", "B"], "rows": [["1"]]}}]}, "row 1 has 1 cells for 2 columns")):
            r = self.build(spec, ok=False)
            self.assertIn(msg, r.stdout + r.stderr, spec)
        self.assertEqual(self.drafts(), [])

    def test_the_template_is_needed(self):
        (self.v.root / "system/templates/adhoc-template.docx").unlink()
        r = self.build({"title": "X"}, ok=False)
        self.assertIn("adhoc-template.docx is missing", r.stdout + r.stderr)

    def test_an_empty_result_says_so(self):
        self.build({"title": "None", "sections": [{"heading": "Nothing", "tracker": {"table": "raid", "type": "Dependency"}}]})
        text = self.text("system/staging/drafts/2026-10-07 None.docx")
        self.assertIn("No RAID items match.", text)
        self.assertNotIn("ID |", text)

    def test_it_reads_the_tracker_but_never_writes_it(self):
        before = self.v.snapshot()
        self.build({"title": "Read only", "sections": [{"tracker": {"table": "actions"}}]})
        data, files = self.v.snapshot()
        keep = lambda fs: {k: v for k, v in fs.items() if not k.startswith("system/staging") and k != "spec.json"}  # noqa: E731
        self.assertEqual((data, keep(files)), (before[0], keep(before[1])))


class BuildAdhocTests(unittest.TestCase):
    def test_text_with_markup_characters_and_line_breaks(self):
        v = Vault()
        try:
            f = v.root / "s.json"
            f.write_text(json.dumps({"title": "A & B <C>", "sections": [{"heading": "H", "table": {"columns": ["X"], "rows": [["a\nb & <c>"]]}}]}))
            out = v.root / "system/staging/drafts/o.docx"          # BL-271: the command line writes only in drafts/
            out.parent.mkdir(parents=True, exist_ok=True)
            r = subprocess.run([sys.executable, str(v.root / "system/scripts/docx_tools.py"), "build-adhoc",
                                str(v.root / "system/templates/adhoc-template.docx"), str(f), str(out)], capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            doc = zipfile.ZipFile(out).read("word/document.xml").decode()
            minidom.parseString(doc)
            self.assertIn("a</w:t><w:br/><w:t", doc)
            self.assertIn("&amp; &lt;c&gt;", doc)
        finally:
            v.cleanup()


if __name__ == "__main__":
    unittest.main()
