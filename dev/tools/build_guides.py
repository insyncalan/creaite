"""Write the two standalone guides from system/templates/help.md (development only).

Run: python3 dev/tools/build_guides.py [--check]

  system/templates/guide-first-day.html   from "# Start here"
  system/templates/guide-how-to.html      from "# How do I…"

They draw the same components, from the same functions (build_dashboard.help_part), with the same CSS as the dashboard's
Help tabs (the marked "Help (BL-84)" section of dashboard.html), in the creaite standard palette, light and dark, with
the fonts embedded: one self-contained file each, no network, linking to each other. Run it whenever help.md changes;
a test (dev/tests/test_help.py) fails while either file is out of date. --check only reports.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "system" / "scripts"))
import build_dashboard as bd  # noqa: E402
import paths  # noqa: E402

GUIDES = {"start": ("guide-first-day.html", "creaite first-day card"), "howto": ("guide-how-to.html", "creaite top-12 card")}   # #158: two cards, not two long guides
BEGIN, END = "/* ===== Help (BL-84) ===== */", "/* ===== end Help (BL-84) ===== */"

# creaite standard, as in the dashboard's Help tokens (light, then dark; data-theme="light" or "dark" overrides the system)
LIGHT = ("--hp-ground:#F3F6F7;--hp-paper:#FFFFFF;--hp-ink:#14212A;--hp-soft:#4D5C66;--hp-hair:#D7DFE3;--hp-teal:#0B6E7F;"
         "--hp-teal-soft:#DCEFF2;--hp-amber:#8A5A00;--hp-amber-soft:#FBF0DA;--hp-green:#2E6B3A;--hp-green-soft:#E3F2E5;")
DARK = ("--hp-ground:#0F1518;--hp-paper:#171E22;--hp-ink:#E4EAED;--hp-soft:#A2AEB5;--hp-hair:#2A343A;--hp-teal:#5FC4D6;"
        "--hp-teal-soft:#16363C;--hp-amber:#F0C66B;--hp-amber-soft:#3A2C10;--hp-green:#9FD6A5;--hp-green-soft:#1D3322;")
FONTS = ('--hp-display:"Schibsted Grotesk","Helvetica Neue",Arial,sans-serif;--hp-body:"Source Sans 3","Segoe UI",system-ui,sans-serif;'
         '--hp-mono:"JetBrains Mono",ui-monospace,Menlo,monospace;'
         '--d2:200ms;')   # v1.9.5 (UI audit P1-8): the dashboard's --d2, read by the copied Help components (.hp-stage)


def components_css():
    """The Help components' CSS, copied from the dashboard template so the two cannot differ."""
    text = (paths.TEMPLATES / "dashboard.html").read_text(encoding="utf-8")
    a, b = text.index(BEGIN), text.index(END)
    return text[a:b + len(END)]


SCALE_BEGIN, SCALE_END = "/* ===== BL-325 scale", "/* ===== end BL-325 scale ===== */"


def scale_css():
    """BL-325: the dashboard's one design scale (type, spacing, radius, shadow, z-index, controls), which the copied Help
    components read; copied from the dashboard template so the guides and Help stay on the same scale."""
    text = (paths.TEMPLATES / "dashboard.html").read_text(encoding="utf-8")
    a, b = text.index(SCALE_BEGIN), text.index(SCALE_END)
    return text[text.index(":root{", a):b].strip()


def page(part_id, text=None):
    file, title = GUIDES[part_id]
    body = bd.help_card(part_id, text)
    faces = bd.help_font_faces()
    return f"""<!doctype html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title}</title>
<!-- Generated by dev/tools/build_guides.py from system/templates/help.md: edit help.md and run it again, never this file.
     Self-contained: no network (the fonts are embedded). Open it in any browser. -->
<style>
{faces}
{scale_css()}
:root{{{LIGHT}{FONTS}}}
@media (prefers-color-scheme:dark){{:root:not([data-theme="light"]){{{DARK}color-scheme:dark}}}}
:root[data-theme="dark"]{{{DARK}color-scheme:dark}}
*{{box-sizing:border-box}}
@page{{size:A4;margin:12mm}}
.hp-top12{{list-style:none;counter-reset:j;margin:0;padding:0;display:grid;gap:10px}}
.hp-topjob{{counter-increment:j;display:grid;grid-template-columns:34px 1fr;gap:0 10px;padding:12px 14px;border:1px solid var(--hp-hair);border-radius:10px;background:var(--hp-paper);break-inside:avoid}}
.hp-topjob::before{{content:counter(j);grid-row:1/4;font:800 20px var(--hp-display);color:var(--hp-teal)}}
.hp-topjob b{{font:700 17px var(--hp-display)}} .hp-topjob span{{color:var(--hp-soft)}} .hp-topjob em{{font-style:normal;font:500 12px var(--hp-mono);color:var(--hp-teal)}}
.hp-wrap kbd{{font:500 12px var(--hp-mono);border:1px solid var(--hp-hair);border-radius:5px;padding:1px 6px}}
@media print{{ .hp-top12 .hp-topjob:nth-child(7){{break-before:page}} .hp-start{{zoom:.78}} body{{background:#fff}} }}
body{{background:var(--hp-ground);color:var(--hp-ink);font:400 var(--fs-lg)/1.5 var(--hp-body);margin:0}}
{components_css()}
</style>
</head>
<body>
<div class="hp-wrap hp-{part_id}">
{body}
</div>
</body>
</html>
"""


def build(text=None):
    """{file name: content} for both guides."""
    return {GUIDES[p][0]: page(p, text) for p in GUIDES}


def main(argv):
    out = build()
    stale = [n for n, c in out.items() if not (paths.TEMPLATES / n).exists() or (paths.TEMPLATES / n).read_text(encoding="utf-8") != c]
    if "--check" in argv:
        print("Guides are up to date." if not stale else "Out of date: " + ", ".join(stale) + ". Run python3 dev/tools/build_guides.py")
        return 1 if stale else 0
    for name, content in out.items():
        (paths.TEMPLATES / name).write_text(content, encoding="utf-8")
        print(f"Wrote system/templates/{name} ({len(content.encode('utf-8')) / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
